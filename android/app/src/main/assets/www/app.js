function scaleDish(d, kcal) {
  const target = Math.max(160, Math.min(kcal || d.kcal, 900));
  const k = target / Math.max(1, d.kcal);
  const n = (x) => Math.max(0, Math.round(x * k));
  return Object.assign({}, d, { kcal: n(d.kcal), p: n(d.p), c: n(d.c), f: n(d.f), g: n(d.g || 200) });
}
function dietOk(d) {
  const diet = (state.user && state.user.diet) || "normal";
  if (diet === "vegan" && !d.veg) return false;
  if (diet === "dia" && d.c > 40 && !d.dia) return false;
  const meat = state.taste && state.taste.meat;
  if (meat && meat !== "none" && d.meat && d.meat !== meat && d.meat !== "none") return false;
  if (meat === "none" && d.meat && d.meat !== "none") return false;
  return true;
}
function closestDish(list, left) {
  const pool = list.filter(dietOk);
  const src = pool.length ? pool : list.filter((d) => !state.user || state.user.diet !== "vegan" || d.veg);
  if (!src.length) return null;
  return src.map((d) => {
    const s = scaleDish(d, Math.max(180, left.kcal));
    const score = Math.abs((left.p || 0) - s.p) * 2 + Math.abs((left.kcal || s.kcal) - s.kcal) / 20;
    return { s, score };
  }).sort((a, b) => a.score - b.score)[0].s;
}
