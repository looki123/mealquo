function changeNote(before, after, reason, beforeKcal) {
  const sum = (list) => Math.round((list || []).reduce((a, i) => a + (+i.kcal || 0), 0));
  const afterKcal = sum(after);
  const was = beforeKcal != null ? Math.round(beforeKcal) : sum(before);
  const key = (i) => (i.n || "").trim().toLowerCase();
  const bmap = new Map((before || []).filter((i) => i.n).map((i) => [key(i), i]));
  const amap = new Map((after || []).filter((i) => i.n).map((i) => [key(i), i]));
  const bits = [];
  for (const [k, it] of amap) {
    const old = bmap.get(k);
    if (!old) bits.push(L("doszło", "додано", "added") + ": " + it.n);
    else if (Math.abs((old.g || 0) - (it.g || 0)) >= 8) bits.push(it.n + " " + Math.round(old.g || 0) + " → " + Math.round(it.g || 0) + " g");
    else if (Math.abs((old.kcal || 0) - (it.kcal || 0)) >= 5) bits.push(it.n + " " + Math.round(old.kcal || 0) + " → " + Math.round(it.kcal || 0) + " kcal");
  }
  for (const [k, it] of bmap) if (!amap.has(k)) bits.push(L("bez", "прибрано", "removed") + ": " + it.n);
  const head = L("Było", "Було", "Was") + " " + was + " → " + afterKcal + " kcal.";
  const why = (reason || "").trim();
  const body = bits.join(". ");
  return [head, why, body].filter(Boolean).join(" ");
}
function matchFoodLoose(name) {
  const s = (name || "").toLowerCase();
  if (!s) return null;
  let best = null, score = 0;
  for (const f of FOODS) {
    const blob = `${f.name.pl} ${f.name.uk} ${f.tags || ""} ${f.id || ""}`.toLowerCase();
    let n = 0;
    if (blob.includes(s)) n += 6;
    for (const w of s.split(/\s+/)) if (w.length > 2 && blob.includes(w)) n += 2;
    if (n > score) { score = n; best = f; }
  }
  return score >= 4 ? best : null;
}
