function clockMinutes(time) {
  const m = /^(\d{1,2}):(\d{2})/.exec(time || "");
  if (!m) return null;
  return (+m[1]) * 60 + (+m[2]);
}
function fromMinutes(min) {
  const x = ((min % 1440) + 1440) % 1440;
  return String(Math.floor(x / 60)).padStart(2, "0") + ":" + String(x % 60).padStart(2, "0");
}
function habitWindows() {
  const today = iso(new Date());
  const start = new Date();
  start.setDate(start.getDate() - 14);
  const startId = iso(start);
  const points = [];
  for (const meal of state.meals || []) {
    if (!meal.date || meal.date >= today || meal.date < startId) continue;
    const min = clockMinutes(meal.time);
    if (min == null) continue;
    points.push({ min, day: meal.date });
  }
  points.sort((a, b) => a.min - b.min);
  const clusters = [];
  for (const pt of points) {
    const last = clusters[clusters.length - 1];
    if (!last || pt.min - last.max > 75) clusters.push({ items: [pt], max: pt.min });
    else { last.items.push(pt); last.max = pt.min; }
  }
  const activeDays = new Set(points.map((p) => p.day)).size;
  const need = activeDays >= 6 ? 3 : 2;
  const windows = [];
  for (const cluster of clusters) {
    const days = new Set(cluster.items.map((i) => i.day));
    if (days.size < need) continue;
    const mins = cluster.items.map((i) => i.min).sort((a, b) => a - b);
    const mid = mins[Math.floor(mins.length / 2)];
    windows.push({
      at: fromMinutes(mid + 20),
      usual: fromMinutes(mid),
      from: mid - 50,
      to: mid + 80,
    });
  }
  return windows.slice(0, 5);
}
