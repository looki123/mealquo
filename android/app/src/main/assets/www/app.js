function ageFromDob(dob) {
  if (!dob) return 30;
  const d = new Date(dob);
  if (Number.isNaN(+d)) return 30;
  const n = new Date();
  let a = n.getFullYear() - d.getFullYear();
  const m = n.getMonth() - d.getMonth();
  if (m < 0 || (m === 0 && n.getDate() < d.getDate())) a--;
  return Math.max(14, Math.min(90, a));
}
function goalPlan(u) {
  const sex = u.sex === "female" ? "female" : "male";
  const weight = Math.max(35, Math.round(+u.weight || 70));
  const height = Math.max(140, Math.round(+u.height || 170));
  const age = ageFromDob(u.dob);
  const bmr = 10 * weight + 6.25 * height - 5 * age + (sex === "female" ? -161 : 5);
  const mult = { low: 1.2, mid: 1.45, high: 1.7 }[u.activity] || 1.45;
  const maintain = Math.max(1200, Math.round(bmr * mult));
  let target = Math.round(+u.targetWeight || weight);
  let goal = u.goal || "keep";
  if (target <= weight - 1) goal = "lose";
  else if (target >= weight + 1) goal = "gain";
  else goal = "keep";
  const pace = u.pace === "easy" || u.pace === "hard" ? u.pace : "normal";
  const floor = sex === "female" ? 1200 : 1500;
  const perKg = 7700;
  let kcal = maintain;
  let kgWeek = 0;
  let days = 0;
  let slow = false;
  const gap = Math.abs(target - weight);
  if (goal === "lose") {
    const maxDef = Math.max(200, maintain - floor);
    const kg = pace === "easy" ? 0.25 : pace === "hard" ? 0.75 : 0.5;
    const wanted = Math.round(kg * perKg / 7);
    const def = Math.min(wanted, maxDef);
    slow = def < wanted - 20;
    kcal = maintain - def;
    kgWeek = Math.round((def * 7 / perKg) * 100) / 100;
    days = Math.max(7, Math.round(gap / kgWeek * 7));
  } else if (goal === "gain") {
    const kg = pace === "easy" ? 0.15 : pace === "hard" ? 0.45 : 0.3;
    const surplus = Math.min(500, Math.round(kg * perKg / 7));
    kcal = maintain + surplus;
    kgWeek = Math.round((surplus * 7 / perKg) * 100) / 100;
    days = Math.max(7, Math.round(gap / kgWeek * 7));
  } else {
    target = weight;
  }
  let pPerKg = goal === "lose" ? 2 : goal === "gain" ? 1.8 : 1.6;
  if (u.diet === "highp") pPerKg = Math.max(pPerKg, 2);
  if (u.diet === "vegan") pPerKg = Math.max(1.6, pPerKg - 0.1);
  const p = Math.round(weight * pPerKg);
  let f = Math.round((kcal * 0.28) / 9);
  let c = Math.round((kcal - p * 4 - f * 9) / 4);
  if (u.diet === "dia") {
    c = Math.round((kcal * 0.3) / 4);
    f = Math.max(25, Math.round((kcal - p * 4 - c * 4) / 9));
  }
  if (c < 40) {
    c = 40;
    f = Math.max(25, Math.round((kcal - p * 4 - c * 4) / 9));
  }
  return { kcal, p, c, f, days, kgWeek, goal, target, from: weight, maintain, slow, pace };
}
function calcPlan(u) {
  u.age = ageFromDob(u.dob);
  if (u.targetWeight) return goalPlan(u);
  const s = u.sex === "female" ? -161 : 5;
  const bmr = 10 * u.weight + 6.25 * u.height - 5 * u.age + s;
  const mult = { low: 1.2, mid: 1.45, high: 1.7 }[u.activity] || 1.45;
  let kcal = Math.round(bmr * mult);
  if (u.goal === "lose") kcal = Math.round(kcal * 0.82);
  if (u.goal === "gain") kcal = Math.round(kcal * 1.12);
  let pPerKg = u.diet === "highp" ? 2.0 : 1.6;
  if (u.diet === "vegan") pPerKg = 1.7;
  const p = Math.round(u.weight * pPerKg);
  let f = Math.round((kcal * 0.28) / 9);
  let c = Math.round((kcal - p * 4 - f * 9) / 4);
  if (u.diet === "dia") {
    c = Math.round((kcal * 0.3) / 4);
    f = Math.round((kcal - p * 4 - c * 4) / 9);
  }
  return { kcal, p, c, f };
}

