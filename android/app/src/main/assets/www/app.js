function bindWheels(onPick) {
  app.querySelectorAll(".wheel-col").forEach((col) => {
    const itemH = 46;
    const items = () => [...col.querySelectorAll(".wheel-item")];
    const mark = () => {
      const i = Math.max(0, Math.min(items().length - 1, Math.round(col.scrollTop / itemH)));
      items().forEach((el, idx) => el.classList.toggle("on", idx === i));
      const el = items()[i];
      if (el) onPick(col.dataset.col, el.dataset.v);
    };
    col.addEventListener("scroll", mark, { passive: true });
    const start = items().findIndex((el) => el.dataset.v === col.dataset.sel);
    requestAnimationFrame(() => {
      col.scrollTop = Math.max(0, start) * itemH;
      mark();
    });
  });
}
