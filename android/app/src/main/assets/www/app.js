function inventDish(used, slot) {
  const bases = LIKES.filter((it) => it.meat || ["eggs", "tofu", "cheese", "mushrooms"].includes(it.id));
  for (let n = 0; n < bases.length * FORMS.length * 6; n++) {
    const b = bases[n % bases.length];
    const f = FORMS[Math.floor(n / bases.length) % FORMS.length];
    const round = Math.floor(n / (bases.length * FORMS.length));
    const tail = round ? ` ${round + 1}` : "";
    const pl = `${b.nom[0]} ${f[0]}${tail}`;
    if (used.has(pl.toLowerCase())) continue;
    const kcal = 260 + (n % 7) * 45;
    const p = b.meat ? 32 + (n % 4) * 3 : 16;
    const c = f[0].includes("ryż") || f[0].includes("kaszą") || f[0].includes("grzance") ? 40 : 14;
    const fAt = Math.max(6, Math.round((kcal - p * 4 - c * 4) / 9));
    return {
      pl, uk: `${b.nom[1]} ${f[1]}${tail}`, en: `${b.nom[2]} ${f[2]}${tail}`,
      g: 280, kcal, p, c, f: fAt, meat: b.meat || "none", veg: b.meat ? 0 : 1,
      where: "all", slot,
    };
  }
  return null;
}
function ideasNow(leftKcal) {
  const slot = dayPart(new Date().getHours());
  const where = placeKey();
  const stamp = `${selectedDay}|${slot}`;
  if (state.ideaBatch && state.ideaBatch.stamp === stamp && (state.ideaBatch.items || []).length) {
    return { slot, where, items: state.ideaBatch.items };
  }
  const diet = (state.user && state.user.diet) || "normal";
  const taste = state.taste || {};
  state.seenIdeas = state.seenIdeas || [];
  const seen = new Set(state.seenIdeas);
  (state.pending || []).forEach((p) => seen.add(String(p.title || "").toLowerCase()));
  (state.meals || []).forEach((m) => seen.add(String(m.title || "").toLowerCase()));
  const placeOk = (d) => !d.where || d.where === where || d.where === "all" || (where === "eu" && (d.where === "pl" || d.where === "ua"));
  const menus = Object.keys(MENUS).reduce((a, id) => a.concat(MENUS[id].items), []);
  let pool = IDEAS.concat(DATES, COOKS, ORDERS, menus).filter((d) => {
    if (d.slot && d.slot !== slot && !(slot === "night" && d.slot === "snack")) return false;
    if (!placeOk(d)) return false;
    if (diet === "vegan" && !d.veg && d.meat && d.meat !== "none") return false;
    if (diet === "dia" && d.c > 40) return false;
    if (taste.drink === "dry" && d.drink === "wine") return false;
    if (seen.has(dishKey(d))) return false;
    return true;
  });
  if (taste.meat || taste.mood || taste.heat) pool = pool.slice().sort((a, b) => tasteScore(b) - tasteScore(a) || b.p - a.p);
  else if (diet === "highp" || (state.user && state.user.goal) === "lose") pool = pool.slice().sort((a, b) => b.p - a.p);
  const light = leftKcal < 320 ? pool.filter((d) => d.kcal <= leftKcal + 80) : pool;
  if (light.length >= 4) pool = light;
  const items = [];
  const used = new Set(seen);
  for (let i = 0; i < pool.length && items.length < 4; i++) {
    const name = dishKey(pool[i]);
    if (used.has(name)) continue;
    used.add(name);
    items.push(pool[i]);
  }
  while (items.length < 4) {
    const made = inventDish(used, slot);
    if (!made) break;
    used.add(dishKey(made));
    items.push(made);
  }
  items.forEach((d) => state.seenIdeas.push(dishKey(d)));
  state.ideaBatch = { stamp, items };
  save();
  return { slot, where, items };
}
