function tasteScore(d) {
  const known = state.taste || {};
  let score = 0;
  const likedMeat = topLikedMeat();
  if (likedMeat && d.meat) score += d.meat === likedMeat ? 8 : (likedMeat === "none" && d.veg ? 6 : -2);
  else if (known.meat && d.meat) score += known.meat === d.meat ? 8 : (known.meat === "none" && d.veg ? 6 : -4);
  ["mood", "heat", "plate", "drink", "end"].forEach((k) => {
    if (!known[k] || !d[k]) return;
    score += known[k] === d[k] ? 3 : -3;
  });
  const name = `${d.pl || ""} ${d.en || ""}`.toLowerCase();
  favoriteRank().slice(0, 5).forEach((x, i) => {
    if (name.includes(x.it.nom[0].toLowerCase())) score += 5 - i;
  });
  return score;
}
